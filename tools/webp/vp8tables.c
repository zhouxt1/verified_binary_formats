/* Print RFC 6386's VP8 tables as Rust consts, straight from the reference
   decoder's headers (compiled, not parsed): tools/webp/vp8tables.sh. */
#include <stdio.h>
#include "dixie.h"
#include "vp8_prob_data.h"
#include "modemv_data.h"
#include "dequant_data.h"

static void flat(const char* name, const char* ty, const char* dims, const void* p, int n, int isint) {
  printf("pub const %s: %s = [", name, dims);
  for (int i = 0; i < n; i++) {
    if (i % 16 == 0) printf("\n    ");
    printf("%d,%s", isint ? ((const int*)p)[i] : ((const unsigned char*)p)[i], i % 16 == 15 ? "" : " ");
  }
  printf("\n];\n");
  (void)ty;
}
#define U8(name, dims, a) flat(#name, "u8", dims, a, sizeof(a), 0)
#define I32(name, dims, a) flat(#name, "i32", dims, a, sizeof(a) / sizeof(int), 1)

int main(void) {
  printf("// Generated by tools/webp/vp8tables.sh from RFC 6386's reference decoder\n"
         "// (section 20: dequant_data.h, modemv_data.h, vp8_prob_data.h). Do not edit.\n"
         "// Multi-dimensional tables are flattened, row-major.\n\n");
  I32(DC_Q, "[i32; 128]", dc_q_lookup);
  I32(AC_Q, "[i32; 128]", ac_q_lookup);
  U8(KF_Y_MODE_PROBS, "[u8; 4]", kf_y_mode_probs);
  U8(KF_UV_MODE_PROBS, "[u8; 3]", kf_uv_mode_probs);
  U8(KF_B_MODE_PROBS, "[u8; 900]", kf_b_mode_probs);
  I32(KF_Y_MODE_TREE, "[i32; 8]", kf_y_mode_tree);
  I32(UV_MODE_TREE, "[i32; 6]", uv_mode_tree);
  I32(B_MODE_TREE, "[i32; 18]", b_mode_tree);
  U8(COEFF_UPDATE_PROBS, "[u8; 1056]", k_coeff_entropy_update_probs);
  U8(DEFAULT_COEFF_PROBS, "[u8; 1056]", k_default_coeff_probs);
  return 0;
}
