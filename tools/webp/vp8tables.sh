#!/bin/bash
# Regenerate vwebp-tool/src/vp8tab.rs from RFC 6386's reference decoder
# (extracted by difftest/webp/rfc/build.sh into difftest/webp/build/rfc).
set -e
cd "$(dirname "$0")/../.."
R=difftest/webp/build/rfc
gcc -w -I$R -include vpx_encoder.h -o $R/vp8tables tools/webp/vp8tables.c
$R/vp8tables > vwebp-tool/src/vp8tab.rs
# The same tables inside verus! for the verified decoder.
python3 - <<'PY'
src = open("vwebp-tool/src/vp8tab.rs").read()
body = src.split("\n\n", 1)[1]
open("vwebp/src/vp8/tab.rs", "w").write('''//! RFC 6386's VP8 tables, for the spec and the decoder alike. Generated by
//! tools/webp/vp8tables.sh from the reference decoder's headers (section
//! 20: dequant_data.h, modemv_data.h, vp8_prob_data.h); do not edit.
//! Multi-dimensional tables are flattened, row-major.
use vstd::prelude::*;

verus! {

''' + body + '''
} // verus!
''')
PY
echo wrote vwebp-tool/src/vp8tab.rs vwebp/src/vp8/tab.rs
